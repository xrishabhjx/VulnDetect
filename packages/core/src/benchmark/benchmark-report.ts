/**
 * Benchmark report formatter — converts BenchmarkSuiteResult to Markdown.
 */
import type { BenchmarkSuiteResult, BenchmarkRunResult } from "./benchmark-runner.js";

function bar(score: number, width = 20): string {
  const filled = Math.round((score / 100) * width);
  return "█".repeat(filled) + "░".repeat(width - filled);
}

function gradeBadge(grade: string): string {
  const badges: Record<string, string> = {
    A: "🟢 A",
    B: "🔵 B",
    C: "🟡 C",
    D: "🟠 D",
    F: "🔴 F",
  };
  return badges[grade] ?? grade;
}

export function formatBenchmarkReport(suite: BenchmarkSuiteResult): string {
  const lines: string[] = [];

  lines.push(`# RSIS Benchmark Report`);
  lines.push(`> Generated: ${new Date(suite.runAt).toLocaleString()}\n`);

  lines.push(`## Summary\n`);
  lines.push(`| Metric | Value |`);
  lines.push(`|--------|-------|`);
  lines.push(`| Repositories evaluated | ${suite.successCount}/${suite.totalRepos} |`);
  lines.push(`| Mean RSIS before remediation | **${suite.meanRsisBefore}**/100 |`);
  lines.push(`| Mean RSIS after remediation (projected) | **${suite.meanRsisAfter}**/100 |`);
  lines.push(`| Mean score improvement | **+${suite.meanDelta}** points |`);
  lines.push(`| Failed scans | ${suite.failCount} |\n`);

  lines.push(`## Per-Repository Results\n`);

  for (const r of suite.results) {
    lines.push(`### ${r.repo.name}`);
    lines.push(`> \`${r.repo.repoUrl}\` · ${r.repo.ecosystem.toUpperCase()} · *${r.repo.description}*\n`);

    if (!r.success) {
      lines.push(`**⚠️ Scan failed:** ${r.error ?? "Unknown error"}\n`);
      continue;
    }

    const delta = r.scoreDelta >= 0 ? `+${r.scoreDelta}` : `${r.scoreDelta}`;

    lines.push(`| | Before | After (Projected) |`);
    lines.push(`|-|--------|-------------------|`);
    lines.push(`| **RSIS Score** | **${r.rsisBefore.totalScore}**/100 | **${r.rsisAfter.totalScore}**/100 |`);
    lines.push(`| **Grade** | ${gradeBadge(r.rsisBefore.grade)} | ${gradeBadge(r.rsisAfter.grade)} |`);
    lines.push(`| Security | ${r.rsisBefore.securityScore.toFixed(1)} | ${r.rsisAfter.securityScore.toFixed(1)} |`);
    lines.push(`| Maintainability | ${r.rsisBefore.maintainabilityScore.toFixed(1)} | ${r.rsisAfter.maintainabilityScore.toFixed(1)} |`);
    lines.push(`| Compatibility | ${r.rsisBefore.compatibilityScore.toFixed(1)} | ${r.rsisAfter.compatibilityScore.toFixed(1)} |\n`);

    lines.push(`**Score improvement: ${delta} points**\n`);
    lines.push(`\`\`\`\nBefore  ${bar(r.rsisBefore.totalScore)} ${r.rsisBefore.totalScore}/100\nAfter   ${bar(r.rsisAfter.totalScore)} ${r.rsisAfter.totalScore}/100\n\`\`\`\n`);

    lines.push(`**Vulnerability Profile:**\n`);
    lines.push(`| Metric | Count |`);
    lines.push(`|--------|-------|`);
    lines.push(`| Total dependencies | ${r.metrics.totalDeps} |`);
    lines.push(`| Total vulnerabilities | ${r.metrics.totalVulns} |`);
    lines.push(`| Critical | ${r.metrics.criticalCount} |`);
    lines.push(`| High | ${r.metrics.highCount} |`);
    lines.push(`| CISA KEV entries | ${r.metrics.kevCount} |`);
    lines.push(`| Fixable (have patch) | ${r.metrics.fixableVulns} (${(r.metrics.remediableRate * 100).toFixed(0)}%) |`);
    lines.push(`| Scan duration | ${r.scanDurationMs}ms |\n`);
  }

  lines.push(`---`);
  lines.push(`*Generated by the RSIS Benchmark Suite — AI-Powered Repository Security Intelligence Platform*`);

  return lines.join("\n");
}
